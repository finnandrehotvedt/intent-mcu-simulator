// The production bundle registry is deliberately finite. Lock data is never
// interpreted as a path, URL or package name. The caller must first match a
// complete allowlisted lock, then selects one of these finite static imports.
export function productionModelBundle(role) {
  if (role === 'retained') return RETAINED_MODEL_LIBRARY_IMPLEMENTATION;
  if (role === 'pre-x66-subcircuit-review-fix-current-migration') {
    return PRE_X66_SUBCIRCUIT_REVIEW_FIX_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x66-bounded-subcircuits-current-migration') {
    return PRE_X66_BOUNDED_SUBCIRCUITS_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x66-legacy-open-review-fix-current-migration') {
    return PRE_X66_LEGACY_OPEN_REVIEW_FIX_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x66-net-labels-current-migration') {
    return PRE_X66_NET_LABELS_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-teaching-review-fix-current-migration') {
    return PRE_TEACHING_REVIEW_FIX_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-teaching-batch-current-migration') {
    return PRE_TEACHING_BATCH_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x92-dispatch-gate-fix-current-migration') {
    return PRE_X92_DISPATCH_GATE_FIX_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x92-runtime-lifetime-fix-current-migration') {
    return PRE_X92_RUNTIME_LIFETIME_FIX_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x92-review-fix-current-migration') {
    return PRE_X92_REVIEW_FIX_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x92-budget-current-migration') {
    return PRE_X92_BUDGET_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x55-model-copy-fix-current-migration') {
    return PRE_X55_MODEL_COPY_FIX_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x55-split-editor-current-migration') {
    return PRE_X55_SPLIT_EDITOR_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x55-noop-apply-fix-current-migration') {
    return PRE_X55_NOOP_APPLY_FIX_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x55-body-lead-fix-current-migration') {
    return PRE_X55_BODY_LEAD_FIX_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x55-body-editor-current-migration') {
    return PRE_X55_BODY_EDITOR_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x55-led-outline-current-migration') {
    return PRE_X55_LED_OUTLINE_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x55-all-profile-current-migration') {
    return PRE_X55_ALL_PROFILE_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x47-repeatable-apply-current-migration') {
    return PRE_X47_REPEATABLE_APPLY_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x47-momentary-control-current-migration') {
    return PRE_X47_MOMENTARY_CONTROL_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x47-repeatable-rejection-current-migration') {
    return PRE_X47_REPEATABLE_REJECTION_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x47-repeatable-current-migration') {
    return PRE_X47_REPEATABLE_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x43-stack-hotpath-current-migration') {
    return PRE_X43_STACK_HOTPATH_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x43-stack-current-migration') {
    return PRE_X43_STACK_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-ux-current-migration') {
    return PRE_UX_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x55-control-label-current-migration') {
    return PRE_X55_CONTROL_LABEL_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x55-current-migration') return PRE_X55_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  if (role === 'prior-current-migration') return PRIOR_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  if (role === 'pre-x47-current-migration') return PRE_X47_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  if (role === 'pre-x47-validation-current-migration') {
    return PRE_X47_VALIDATION_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x47-ui-current-migration') {
    return PRE_X47_UI_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'pre-x47-async-current-migration') {
    return PRE_X47_ASYNC_CURRENT_MODEL_LIBRARY_MIGRATION_IMPLEMENTATION;
  }
  if (role === 'current') return CURRENT_MODEL_LIBRARY_IMPLEMENTATION;
  throw new TypeError('MODEL_LIBRARY_REGISTRY_SELECTION');
}
